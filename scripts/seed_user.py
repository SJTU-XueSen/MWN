def gen_daily(date: datetime) -> tuple[str, str]:
    """为普通日子生成日记内容（星期 × 月份 × 随机细节，含约 1/6 消极波动）"""
    # 约 1/6 概率进入消极日（真实人生的起伏）
    if random.random() < 0.17:
        return random.choice(BAD_POOL), random.choice(["低落", "烦躁", "emo", "疲惫", "焦虑", "迷茫"])
    wd = WEEKDAY_POOL[date.weekday()]
    mp = MONTH_POOL.get(date.month, ["今天和往常一样。"])
    parts = [random.choice(wd), random.choice(mp)]
    # 55% 概率加一个生活细节
    if random.random() < 0.55:
        parts.append(random.choice(DETAIL_POOL))
    return " ".join(parts), random.choice(MOOD_POOL)


