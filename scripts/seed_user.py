async def main():
    async with AsyncSessionLocal() as db:
        user = await get_user_by_username(db, USERNAME)
        if not user:
            user = await create_user(db, USERNAME, f"{USERNAME}@mirror.local", PASSWORD, "吴同学", True)
            print(f"创建用户 {USERNAME}")
        uid = user.id

        # ── 清空该用户全部数据 ──
        for model in (DailyRecord, LifeEvent, LifeMemory, PersonaProfile, InterestTrack,
                      LifeGoal, Simulation, FutureSelf, ChatMessage, GrowthReport):
            await db.execute(delete(model).where(model.user_id == uid))
        await db.commit()
        try:
            from backend.services.vector_store import delete_user_data

            delete_user_data(uid)
        except Exception:
            pass
        print("已清空旧数据")

        # ── 生成全部日记日期（先建记录，再并发全量 LLM 分析） ──
        handwritten = {(y, m, d): (content, mood) for m, d, y, content, mood in HANDWRITTEN}
        record_days: list[tuple[datetime, str, str]] = []
        cur = START
        while cur <= END:
            key = (cur.year, cur.month, cur.day)
            if key in handwritten:
                content, mood = handwritten[key]
            else:
                content, mood = gen_daily(cur)
            record_days.append((cur, content, mood))
            cur += timedelta(days=1)

        for date, content, mood in record_days:
            db.add(DailyRecord(user_id=uid, content=content, mood=mood, record_date=date))
        await db.commit()
        print(f"已创建 {len(record_days)} 条记录，开始全量 AI 分析（并发）...")

        # 并发 LLM 分析（每条独立 session，LLM 优先失败回退规则引擎）
        from backend.services.memory_service import process_daily_record as _pdr
        from backend.services.vector_store import add_journal

        sem = asyncio.Semaphore(8)
        ok = 0
        failed = 0

        async def analyze_one(date: datetime, content: str, mood: str):
            nonlocal ok, failed
            async with sem:
                async with AsyncSessionLocal() as sdb:
                    record = (
                        await sdb.execute(
                            select(DailyRecord).where(
                                DailyRecord.user_id == uid, DailyRecord.record_date == date
                            )
                        )
                    ).scalar_one_or_none()
                    if not record:
                        return
                    try:
                        await _pdr(sdb, record, uid)  # LLM 优先，失败自动规则回退
                        ok += 1
                    except Exception as e:
                        failed += 1
                        if failed <= 5:
                            print(f"分析失败 {date}: {e}")
                    try:
                        add_journal(record.id, uid, content, {"mood": mood, "date": str(date)})
                    except Exception:
                        pass

        await asyncio.gather(*[analyze_one(d, c, m) for d, c, m in record_days])
        print(f"AI 分析完成：成功 {ok} 条 / 失败 {failed} 条（失败已由规则引擎兜底）")

        # ── 注入人生事件 ──
        for title, desc, etype, year, month in EVENTS:
            await create_event(db, uid, title, desc, etype, datetime(year, month, 15))
        print(f"已注入 {len(EVENTS)} 个人生事件")

        # ── 注入目标 ──
        for title, gtype, importance, period in GOALS:
            db.add(LifeGoal(user_id=uid, title=title, goal_type=gtype,
                            importance=importance, target_period=period, status="active"))
        await db.commit()
        print(f"已注入 {len(GOALS)} 个目标")

        # ── 生成人格 + 模拟 + 报告 ──
        persona = await generate_persona(db, uid, "数据注入后生成")
        print(f"人格已生成: {persona.persona_type} (置信度 {persona.confidence})")
        sim = await run_simulation(db, uid, "further_study",
                                   "考研深造人工智能方向，同时兼顾工程实践与感情生活")
        print(f"模拟已生成: {len(sim.output_paths or [])} 条路径")
        await generate_report(db, uid, f"成长报告 {datetime.utcnow().strftime('%Y.%m.%d')}",
                              START, END, "")
        print("报告已生成")

        user.skill_tags = ["Python", "机器学习", "强化学习", "嵌入式", "机器人", "算法", "数学"]
        await db.commit()
        print(f"\n完成！{USERNAME}：{llm_count + rule_count} 条日记 + {len(EVENTS)} 事件 + {len(GOALS)} 目标 + 人格/模拟/报告")


asyncio.run(main())
